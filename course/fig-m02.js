// Отравление адреса: поддельный адрес с теми же первыми и последними знаками.
function addressPoison({ seed = 11 } = {}) {
  const r = rng(seed), hex = (n) => Array.from({ length: n }, () => "0123456789abcdef"[Math.floor(r() * 16)]).join("");
  const head = hex(4), tail = hex(4), real = `0x${head}${hex(32)}${tail}`, fake = `0x${head}${hex(32)}${tail}`;
  const body = txt(10, 24, "В истории переводов появился «ваш» адрес — его прислал мошенник переводом на 0.", { size: 12 }) +
    txt(10, 62, "Ваш:", { size: 12, color: C.dim }) + txt(70, 62, real, { size: 12, color: C.green }) +
    txt(10, 92, "Чужой:", { size: 12, color: C.dim }) + txt(70, 92, fake, { size: 12, color: C.red }) +
    txt(10, 130, "Начало и конец совпадают — середина другая. Копируйте адрес из надёжного места, а не из истории;", { size: 12, color: C.dim }) +
    txt(10, 150, "сверяйте целиком на экране аппаратного кошелька; сначала отправьте пробную малую сумму.", { size: 12, color: C.dim }) +
    txt(10, 178, "(Адреса на рисунке выдуманы.)", { size: 11, color: C.dim });
  return svg(600, 190, body, "Пример поддельного адреса с совпадающим началом и концом");
}

