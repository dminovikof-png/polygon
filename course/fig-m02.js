// Разрешение смарт-контракту тратить ваши токены. step 0..3
function approval({ step = 0 } = {}) {
  const caps = ["Вы хотите обменять 100 USDT на сайте обмена.", "Сайт просит разрешение (approve): «контракт может тратить ваши USDT» — часто без предела.", "Обмен прошёл. Разрешение осталось: контракт и сейчас может забрать все USDT кошелька.", "Если контракт взломан или сайт был поддельным — токены уходят без вашей новой подписи. Ненужные разрешения отзывают."];
  let body = txt(10, 22, caps[step], { size: 12 });
  body += box(10, 60, 170, 110, "Ваш кошелёк", [step === 3 ? "USDT: 0" : step >= 2 ? "USDT: 4 900" : "USDT: 5 000"], { color: step === 3 ? C.red : C.blue });
  body += box(420, 60, 170, 110, "Контракт", [step >= 1 ? "разрешено: ∞ USDT" : "разрешений нет"], { color: step >= 1 ? C.gold : C.line });
  if (step >= 1) body += arrow(182, 95, 418, 95, { color: C.gold }) + txt(300, 88, "approve(∞)", { size: 12, anchor: "middle", color: C.gold });
  if (step >= 2) body += arrow(418, 140, 182, 140, { color: C.green, dash: step === 2 }) + txt(300, 160, step === 3 ? "transferFrom: всё" : "обмен 100 USDT", { size: 12, anchor: "middle", color: step === 3 ? C.red : C.green });
  if (step === 3) body += txt(300, 200, "Отзыв: в кошельке или на странице проверки разрешений обозревателя блоков", { size: 12, anchor: "middle", color: C.dim });
  return svg(600, 215, body, "Как работает разрешение смарт-контракту");
}

