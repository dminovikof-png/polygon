// Эмиссия: сколько должен расти спрос, чтобы цена просто стояла на месте.
function dilution() {
  const rows = [["Bitcoin, 2026", 0.8], ["Ethereum (выпуск минус сжигание)", 0.5], ["Типичная сеть PoS", 5], ["Новый токен с разблокировками", 40], ["Фарминг-токен", 150]];
  let body = txt(10, 20, "Выпуск новых монет в год (примерные значения) = сколько спроса нужно добавить, чтобы цена не упала.", { size: 12 });
  rows.forEach(([n, p], i) => {
    const y = 40 + i * 36, len = Math.min(300, Math.log10(1 + p) * 140);
    body += txt(10, y + 17, n, { size: 11 }) + `<rect x="230" y="${y}" width="${Math.max(3, len)}" height="24" rx="4" fill="${p > 20 ? C.red : p > 3 ? C.gold : C.green}" opacity="0.85"/>` + txt(238 + Math.max(3, len), y + 17, `${fmt(p, p < 1 ? 1 : 0)} % в год`, { size: 12 });
  });
  body += txt(10, 232, "Шкала длины полос логарифмическая. Точные цифры по каждой монете меняются — сверяйте по её обозревателю.", { size: 11, color: C.dim });
  return svg(600, 242, body, "Годовая эмиссия разных монет");
}

// Сеть работала, цена — нет: цена BTC от максимума 2021 года до дна 2022 года.
function priceVsNetwork() {
  const d = DATA.btc, from = dayIndex(d.t0, "2021-01-01"), to = dayIndex(d.t0, "2023-12-31");
  const c = d.c.slice(from, to + 1), pts = c.map((v, i) => [i, v]);
  const iMax = c.indexOf(Math.max(...c)), iMin = c.indexOf(Math.min(...c.slice(iMax)), iMax);
  const body = plot([{ pts, color: C.gold }], { x0: 70, y0: 40, w: 500, h: 160, yfmt: (v) => "$" + fmt(v / 1000) + " тыс.", xticks: yearTicks(d.t0 + from * 86400, c.length).concat([[0, "2021"]]),
    marks: [{ x: iMax, y: c[iMax], label: `максимум $${fmt(c[iMax])}`, dy: -8 }, { x: iMin, y: c[iMin], color: C.red, label: `дно $${fmt(c[iMin])}: ${fmt((c[iMin] / c[iMax] - 1) * 100)} %`, dy: 18 }] }) +
    txt(10, 20, "Блоки шли каждые 10 минут, сеть не останавливалась ни на день. Цена за год упала больше чем на три четверти.", { size: 12 });
  return svg(600, 245, body, "Цена BTC с 2021 по 2023 год");
}

// Ончейн-метрики: что меряют и где обманывают.
function onchainPitfalls() {
  const items = [["TVL", "двойной счёт: один доллар", "в трёх протоколах = $3"], ["Число адресов", "один человек — тысячи", "адресов; боты"], ["Объём торгов", "сделки с самим собой", "ради наград"], ["Комиссии сети", "трудно подделать:", "за них платят"], ["Выручка держателям", "лучше всего, но", "смотрите, откуда она"], ["Приток на биржи", "проект: знак менялся", "5 лет из 7"]];
  let body = txt(10, 20, "Чем дороже подделать метрику, тем больше ей можно верить.", { size: 13 });
  items.forEach(([t, a, b], i) => { body += box(5 + (i % 3) * 198, 34 + Math.floor(i / 3) * 104, 190, 94, t, [a, b], { color: i === 3 || i === 4 ? C.green : C.gold, size: 13 }); });
  return svg(600, 246, body, "Ончейн-метрики и их подводные камни");
}

export default { valueAccrual, dilution, priceVsNetwork, onchainPitfalls };
