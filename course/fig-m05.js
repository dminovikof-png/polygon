function ratesCurve({ u = null } = {}) {
  const pts = Array.from({ length: 101 }, (_, i) => i / 100);
  const series = [{ pts: pts.map((x) => [x * 100, rates(x).borrow * 100]), color: C.red, label: "платит заёмщик" }, { pts: pts.map((x) => [x * 100, rates(x).supply * 100]), color: C.green, label: "получает вкладчик" }];
  const marks = u != null ? [{ x: u * 100, y: rates(u).borrow * 100, color: C.red, label: `${fmt(rates(u).borrow * 100, 1)} %` }, { x: u * 100, y: rates(u).supply * 100, color: C.green, label: `${fmt(rates(u).supply * 100, 1)} %` }] : [];
  const body = plot(series, { x0: 55, y0: 40, w: 520, h: 170, ymin: 0, xmin: 0, xmax: 100, yfmt: (v) => fmt(v) + " %", xlab: "загрузка пула: какая доля внесённого взята в долг, %", marks }) +
    txt(10, 20, "Ставка зависит от спроса на займы. После 80 % загрузки она резко растёт (пример параметров).", { size: 12 });
  return svg(600, 252, body, "Ставки займа и вклада в зависимости от загрузки пула");
}

