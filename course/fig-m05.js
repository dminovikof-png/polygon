// Слои риска складываются: вероятность, что хотя бы один сработает.
export function stackRisk(ps) { return 1 - ps.reduce((a, p) => a * (1 - p), 1); }
function riskStack() {
  const layers = [["Сеть (L1/L2)", 0.005], ["Мост", 0.03], ["Смарт-контракт протокола", 0.02], ["Оракул", 0.01], ["Ключи администратора", 0.01], ["Стейблкоин или токен-расписка", 0.01]];
  let body = txt(10, 20, "Деньги в DeFi лежат на нескольких слоях сразу. Цифры — пример, а не оценка конкретных протоколов.", { size: 12 }), acc = [];
  layers.forEach(([name, p], i) => {
    acc.push(p);
    const y = 34 + i * 30;
    body += `<rect x="10" y="${y}" width="${200 + i * 50}" height="24" rx="5" fill="${C.card}" stroke="${C.violet}"/>` + txt(20, y + 17, `${name}: ${fmt(p * 100, 1)} % в год`, { size: 12 });
    body += txt(590, y + 17, `вместе: ${fmt(stackRisk(acc) * 100, 1)} %`, { size: 12, anchor: "end", color: C.gold });
  });
  body += txt(10, 228, `Шесть «маленьких» рисков вместе дают ${fmt(stackRisk(acc) * 100, 1)} % в год — сравнимо с обещанной доходностью многих вкладов.`, { size: 12, color: C.dim });
  return svg(600, 240, body, "Как риски слоёв DeFi складываются");
}

