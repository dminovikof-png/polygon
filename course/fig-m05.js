// Мост: заблокировать здесь, выпустить расписку там. step 0..3
function bridge({ step = 0 } = {}) {
  const caps = ["Вы хотите перенести 10 ETH из сети A в сеть B.", "Мост принимает ETH в свой контракт-хранилище в сети A.", "В сети B мост выпускает 10 «обёрнутых» ETH — расписку на то, что лежит в хранилище.", "Если хранилище взломано, ETH уходят, а расписки в сети B остаются без обеспечения и дешевеют."];
  let body = txt(10, 20, caps[step], { size: 12 });
  body += box(10, 40, 270, 150, "Сеть A", [], { color: C.blue }) + box(320, 40, 270, 150, "Сеть B", [], { color: C.violet });
  body += box(30, 80, 120, 60, "Вы: " + (step === 0 ? "10 ETH" : "0 ETH"), [], { size: 12 });
  body += box(160, 80, 110, 90, "Хранилище", [step === 3 ? "0 ETH (взлом)" : step >= 1 ? "10 ETH" : "—"], { color: step === 3 ? C.red : C.gold, size: 12 });
  if (step >= 1) body += arrow(150, 110, 158, 110);
  if (step >= 2) body += arrow(272, 125, 338, 125, { dash: true }) + box(340, 80, 230, 90, "Вы: 10 обёрнутых ETH", [step === 3 ? "обеспечения нет" : "обеспечены хранилищем"], { color: step === 3 ? C.red : C.green, size: 12 });
  return svg(600, 200, body, "Как работает мост между сетями");
}

